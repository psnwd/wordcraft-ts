"use client";

import { useEffect, useRef, useState } from "react";
import { mountEditor, type WordCraftEditor } from "wordcraft-ts";

const BACKEND = "Python"; // label only; the code is identical for the TypeScript backend
const PREVIEW_CHARS = 200_000; // a textarea chokes on megabytes: past this the full JSON stays in memory

const SAMPLE_ROWS = JSON.stringify(
  [
    { item: "Letterpress paper", qty: 12, price: 4.5 },
    { item: "Linocut ink", qty: 3, price: 12 },
    { item: "Brayer", qty: 2, price: 18.75, note: "medium" },
  ],
  null,
  2,
);

interface Analysis {
  words: number;
  tables: string[][][];
  outline: { level: number; text: string }[];
  pictures: number;
  table_shapes: { rows: number; cols: number }[];
  sections: { orientation: string }[];
  lists: { bullets: number; numbered: number };
  footer_has_page_numbers: boolean;
}
type Result = { kind: "text"; text: string } | { kind: "error"; text: string } | { kind: "analysis"; a: Analysis };

/** Call a route; throw the server's {"error"} message on failure. */
async function api(path: string, body: BodyInit, headers?: HeadersInit): Promise<Response> {
  const res = await fetch(path, { method: "POST", body, headers });
  if (!res.ok) throw new Error(await res.json().then((j) => j.error, () => res.statusText));
  return res;
}
const JSON_HEADERS = { "Content-Type": "application/json" };

export default function Automation() {
  const canvas = useRef<HTMLCanvasElement>(null);
  const editor = useRef<WordCraftEditor | null>(null);
  const fileInput = useRef<HTMLInputElement>(null);
  const specText = useRef(""); // the JSON that is sent, whatever the textarea shows
  const [status, setStatus] = useState("loading…");
  const [mode, setMode] = useState<"table" | "report">("table");
  const [busy, setBusy] = useState(false);
  const [result, setResult] = useState<Result>({ kind: "text", text: `${BACKEND}'s answer appears here.` });
  // table mode
  const [rows, setRows] = useState(SAMPLE_ROWS);
  const [totals, setTotals] = useState(true);
  // report mode
  const [params, setParams] = useState({ company: "Alder Street Press", year: 2025, seed: 7, regions: 4, appendix_rows: 80, charts: true });
  const [specView, setSpecView] = useState(""); // what the textarea shows
  const [specBig, setSpecBig] = useState(false);
  const [specInfo, setSpecInfo] = useState("");

  useEffect(() => {
    let cancelled = false;
    let ed: WordCraftEditor | undefined;
    mountEditor(canvas.current!)
      .then((e) => {
        if (cancelled) return e.destroy(); // StrictMode runs effects twice in dev
        ed = editor.current = e;
        e.onDirty((d) => setStatus(d ? "ready · unsaved" : "ready"));
        setStatus("ready");
      })
      .catch((e) => !cancelled && setStatus(`failed: ${e}`));
    return () => {
      cancelled = true;
      ed?.destroy();
    };
  }, []);

  const ready = status.startsWith("ready");
  const text = (t: string) => setResult({ kind: "text", text: t });
  const fail = (e: unknown) => setResult({ kind: "error", text: String(e) });

  function setSpec(t: string) {
    specText.current = t;
    const big = t.length > PREVIEW_CHARS;
    setSpecBig(big);
    setSpecView(big ? `${t.slice(0, 4000)}\n… (${(t.length / 1024 / 1024).toFixed(1)} MB loaded; preview only)` : t);
    if (!t) return setSpecInfo("");
    let info = `${(t.length / 1024).toFixed(0)} KB`;
    try {
      info += `, ${(JSON.parse(t).blocks ?? []).length} blocks`;
    } catch {
      info += " (not valid JSON yet)";
    }
    setSpecInfo(big ? `${info} · preview only` : info);
  }

  /** POST a JSON string, open the .docx that comes back. */
  async function build(path: string, json: string, what: string) {
    setBusy(true);
    text(`Building in ${BACKEND}…`);
    try {
      const t0 = performance.now();
      const res = await api(path, json, JSON_HEADERS);
      const bytes = new Uint8Array(await res.arrayBuffer());
      await editor.current!.load(bytes, "document.docx");
      text(`${what}: ${(bytes.length / 1024).toFixed(0)} KB built in ${((performance.now() - t0) / 1000).toFixed(1)} s and opened in the editor.`);
    } catch (e) {
      fail(e);
    } finally {
      setBusy(false);
    }
  }

  function buildTable() {
    try {
      void build("/api/generate", JSON.stringify({ title: "Order report", intro: `Generated by ${BACKEND} from JSON.`, rows: JSON.parse(rows), totals }), "Table");
    } catch (e) {
      fail(e);
    }
  }

  async function makeSample() {
    setBusy(true);
    text(`Creating sample JSON in ${BACKEND}…`);
    try {
      const res = await api("/api/sample", JSON.stringify(params), JSON_HEADERS);
      setSpec(JSON.stringify(await res.json()));
      text("Sample JSON created. Edit it if you like, then build the report.");
    } catch (e) {
      fail(e);
    } finally {
      setBusy(false);
    }
  }

  function buildReport() {
    if (!specText.current.trim()) return fail("Create a sample or load a JSON file first.");
    try {
      JSON.parse(specText.current);
    } catch (e) {
      return fail(`The JSON is not valid: ${e}`);
    }
    void build("/api/report", specText.current, "Report"); // the string as is: no parse + stringify for a big document
  }

  async function analyze() {
    try {
      const res = await api("/api/analyze", (await editor.current!.export("docx")) as BodyInit);
      setResult({ kind: "analysis", a: await res.json() });
    } catch (e) {
      fail(e);
    }
  }

  const num = (k: keyof typeof params) => (e: React.ChangeEvent<HTMLInputElement>) => setParams({ ...params, [k]: Number(e.target.value) });

  return (
    <div className="app">
      <div className="bar">
        <span className="brand">WordCraft · {BACKEND} automation</span>
        <span className="spacer" />
        <span className="status">{status}</span>
      </div>
      <div className="stage"><canvas ref={canvas} /></div>
      <aside>
        <h3>1 · Generate in {BACKEND}</h3>
        <div className="tabs">
          <button aria-pressed={mode === "table"} onClick={() => setMode("table")}>Table from JSON</button>
          <button aria-pressed={mode === "report"} onClick={() => setMode("report")}>Report from JSON</button>
        </div>

        {mode === "table" ? (
          <>
            <textarea value={rows} onChange={(e) => setRows(e.target.value)} spellCheck={false} />
            <label className="check"><input type="checkbox" checked={totals} onChange={(e) => setTotals(e.target.checked)} /> Add a totals row for numeric columns</label>
            <button className="primary" disabled={!ready || busy} onClick={buildTable}>Generate table in {BACKEND} → open in editor</button>
          </>
        ) : (
          <>
            <div className="grid2">
              <label className="wide">Company <input value={params.company} maxLength={80} onChange={(e) => setParams({ ...params, company: e.target.value })} /></label>
              <label>Year <input type="number" value={params.year} min={1990} max={2100} onChange={num("year")} /></label>
              <label>Seed <input type="number" value={params.seed} onChange={num("seed")} /></label>
              <label>Regions
                <select value={params.regions} onChange={(e) => setParams({ ...params, regions: Number(e.target.value) })}>
                  {[2, 3, 4, 5, 6].map((n) => <option key={n}>{n}</option>)}
                </select>
              </label>
              <label>Appendix rows <input type="number" value={params.appendix_rows} min={0} max={50000} onChange={num("appendix_rows")} /></label>
              <label className="check wide"><input type="checkbox" checked={params.charts} onChange={(e) => setParams({ ...params, charts: e.target.checked })} /> Include charts</label>
            </div>
            <button disabled={!ready || busy} onClick={makeSample}>Create sample JSON in {BACKEND}</button>
            <label>Report JSON
              <textarea
                value={specView}
                readOnly={specBig}
                spellCheck={false}
                placeholder="Paste a report spec, load a .json file, or create a sample (schema: automation/REPORT_JSON.md)"
                onChange={(e) => setSpec(e.target.value)}
              />
            </label>
            <div className="row">
              <button onClick={() => fileInput.current?.click()}>Load .json file…</button>
              <button onClick={() => setSpec("")}>Clear</button>
              <span className="status">{specInfo}</span>
              <input ref={fileInput} type="file" accept=".json,application/json" hidden
                onChange={async (e) => { const f = e.target.files?.[0]; if (f) setSpec(await f.text()); e.target.value = ""; }} />
            </div>
            <button className="primary" disabled={!ready || busy} onClick={buildReport}>Build report from JSON → open in editor</button>
          </>
        )}

        <h3>2 · Edit, then</h3>
        <button disabled={!ready} onClick={analyze}>Analyze in {BACKEND} ← read it back</button>
        <div className={`result${result.kind === "error" ? " err" : ""}`}>
          {result.kind === "analysis" ? <AnalysisView a={result.a} /> : result.text}
        </div>
      </aside>
    </div>
  );
}

function AnalysisView({ a }: { a: Analysis }) {
  const plural = (n: number, w: string) => `${n} ${w}${n === 1 ? "" : "s"}`;
  const facts = [
    `${a.words.toLocaleString()} words`,
    `${plural(a.tables.length, "table")} (largest ${Math.max(0, ...a.table_shapes.map((t) => t.rows))} rows)`,
    plural(a.pictures, "picture"),
    `${plural(a.sections.length, "section")}: ${a.sections.map((s) => s.orientation).join(" → ")}`,
    `${a.lists.bullets} bullets, ${a.lists.numbered} numbered`,
    a.footer_has_page_numbers ? "page numbers ✓" : "no page numbers",
  ];
  return (
    <>
      <div className="chips">{facts.map((f) => <span key={f} className="chip">{f}</span>)}</div>
      <ul className="outline">{a.outline.map((h, i) => <li key={i} className={`l${Math.min(h.level, 3)}`}>{h.text}</li>)}</ul>
      <details><summary>Table contents (JSON)</summary><pre>{JSON.stringify(a.tables.map((t) => t.slice(0, 40)), null, 1)}</pre></details>
    </>
  );
}
