"use client";

import { useEffect, useRef, useState } from "react";
import { mountEditor, type WordCraftEditor } from "wordcraft-ts";

const SAMPLE = JSON.stringify(
  [
    { item: "Letterpress paper", qty: 12, price: 4.5 },
    { item: "Linocut ink", qty: 3, price: 12 },
    { item: "Brayer", qty: 2, price: 18.75, note: "medium" },
  ],
  null,
  2,
);

/** Call a Python server; throw its {"error"} message on failure. */
async function api(path: string, body: BodyInit, headers?: HeadersInit): Promise<Response> {
  const res = await fetch(path, { method: "POST", body, headers });
  if (!res.ok) throw new Error(await res.json().then((j) => j.error, () => res.statusText));
  return res;
}

export default function Automation() {
  const canvas = useRef<HTMLCanvasElement>(null);
  const editor = useRef<WordCraftEditor | null>(null);
  const [status, setStatus] = useState("loading…");
  const [data, setData] = useState(SAMPLE);
  const [totals, setTotals] = useState(true);
  const [out, setOut] = useState("Python's answer appears here.");
  const [isError, setIsError] = useState(false);

  useEffect(() => {
    let cancelled = false;
    let ed: WordCraftEditor | undefined;
    mountEditor(canvas.current!)
      .then((e) => {
        if (cancelled) return e.destroy(); // StrictMode runs effects twice in dev
        ed = editor.current = e;
        e.onDirty((d) => setStatus(d ? "ready · unsaved" : "ready"));
        setStatus("ready");
      })
      .catch((e) => !cancelled && setStatus(`failed: ${e}`));
    return () => {
      cancelled = true;
      ed?.destroy();
    };
  }, []);

  const show = (text: string, error = false) => (setOut(text), setIsError(error));
  const ready = status.startsWith("ready");

  async function generate() {
    try {
      const res = await api(
        "/api/generate",
        JSON.stringify({ title: "Order report", intro: "Generated by the Python server from JSON.", rows: JSON.parse(data), totals }),
        { "Content-Type": "application/json" },
      );
      await editor.current!.load(new Uint8Array(await res.arrayBuffer()), "report.docx");
      show("Document generated by the Python server and opened in the editor.");
    } catch (e) {
      show(String(e), true);
    }
  }

  async function analyze() {
    try {
      const res = await api("/api/analyze", (await editor.current!.export("docx")) as BodyInit);
      show(JSON.stringify(await res.json(), null, 2));
    } catch (e) {
      show(String(e), true);
    }
  }

  return (
    <div className="app">
      <div className="bar">
        <span className="brand">WordCraft · Python automation</span>
        <span className="spacer" />
        <span className="status">{status}</span>
      </div>
      <div className="stage"><canvas ref={canvas} /></div>
      <aside>
        <h3>1 · Data (JSON rows)</h3>
        <textarea value={data} onChange={(e) => setData(e.target.value)} spellCheck={false} />
        <label><input type="checkbox" checked={totals} onChange={(e) => setTotals(e.target.checked)} /> Add a totals row for numeric columns</label>
        <button className="primary" disabled={!ready} onClick={generate}>Generate in Python → open in editor</button>
        <h3>2 · Edit the document, then</h3>
        <button disabled={!ready} onClick={analyze}>Analyze in Python ← read tables back</button>
        <pre className={isError ? "err" : ""}>{out}</pre>
      </aside>
    </div>
  );
}
