interface Analysis {
  words: number;
  headings: string[];
  tables: string[][][]; // cell contents
  outline: { level: number; text: string }[];
  pictures: number;
  table_shapes: { rows: number; cols: number }[];
  sections: { orientation: string }[];
  lists: { bullets: number; numbered: number };
  footer_has_page_numbers: boolean;
}

